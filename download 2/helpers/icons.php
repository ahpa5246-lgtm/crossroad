function icon(string $name, int|string|null $size = null, string $class = ''): string
{
    $paths = icon_paths();
    if (!isset($paths[$name])) return '';
    $cls = 'ic ic-' . $name . ($class !== '' ? ' ' . $class : '');
    $sz  = $size !== null && $size !== '' ? ' width="' . (int)$size . '" height="' . (int)$size . '"' : '';
    return '<svg class="' . htmlspecialchars($cls, ENT_QUOTES) . '"' . $sz
         . ' viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">'
         . $paths[$name] . '</svg>';
}

/** Regex matching a single emoji / pictograph (with optional variation selectors, ZWJ, skin tones). */
function emoji_regex(): string
{
    $base = '[\x{1F000}-\x{1FAFF}\x{2600}-\x{27BF}\x{2B00}-\x{2BFF}\x{2800}-\x{28FF}\x{229E}\x{2705}\x{274C}\x{23CF}\x{2328}\x{23E9}-\x{23FA}\x{25B6}\x{25C0}\x{25AB}\x{25AA}\x{25B2}\x{25BC}\x{25BD}\x{25EB}\x{25CB}\x{25CF}\x{2139}]';
    $mod  = '(?:\x{FE0F}|[\x{1F3FB}-\x{1F3FF}])*';
    return '/' . $base . $mod . '(?:\x{200D}' . $base . $mod . ')*/u';
}

/** Remove emoji (and one adjacent space) from plain text. */
function strip_emoji(string $s): string
{
    $s = preg_replace(emoji_regex(), '', $s) ?? $s;
    $s = preg_replace('/\x{FE0F}/u', '', $s) ?? $s;
    return preg_replace('/[ \t]{2,}/', ' ', $s) ?? $s;
}

/** Convert emoji found in an HTML fragment into inline SVG icons (text nodes only). */
function emoji_to_icons(string $html): string
{
    if ($html === '' || !preg_match(emoji_regex(), $html)) return $html;
    $map = emoji_icon_map();
    $parts = preg_split(
        '#(<script\b.*?</script>|<style\b.*?</style>|<title\b.*?</title>|<option\b.*?</option>|<textarea\b.*?</textarea>|<!--.*?-->|<[^>]+>)#is',
        $html, -1, PREG_SPLIT_DELIM_CAPTURE
    );
    if ($parts === false) return $html;
    foreach ($parts as $i => $seg) {
        if ($seg === '' || !preg_match(emoji_regex(), $seg)) continue;
        if ($seg[0] === '<') {                         // tag / script / style / option …
            $parts[$i] = strip_emoji($seg);
            continue;
        }
        $parts[$i] = preg_replace_callback(emoji_regex(), function ($m) use ($map) {
            $ch = preg_replace('/[\x{FE0F}\x{200D}\x{1F3FB}-\x{1F3FF}]/u', '', $m[0]);
            $name = $map[$ch] ?? null;
            return $name ? icon($name) : '';
        }, $seg);
    }
    return implode('', $parts);
}

/** Output-buffer callback — only touches HTML responses. */
function emoji_output_filter(string $buffer): string
{
    foreach (headers_list() as $h) {
        if (stripos($h, 'content-type:') === 0 && stripos($h, 'text/html') === false) return $buffer;
    }
    return emoji_to_icons($buffer);
}
